"""Write docs/zones.md: every coastal waters zone BOM currently forecasts, grouped by state and region, from
the live forecast products. Run again when BOM changes its zones:

    python tools/list_zones.py > docs/zones.md
"""

import pathlib
import sys
import time
from collections import defaultdict

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bom_ftp  # noqa: E402

LOCAL = {"IDN11013", "IDV10465", "IDT12460", "IDS10035", "IDW11500"}
STATE_ORDER = ["NSW", "VIC", "QLD", "SA", "TAS", "WA", "NT"]
# Combined local waters zones that carry a forecast in some issues only, so a single run can miss them
# (seen 21 October 2026). Listed separately when the live products don't have them.
SOMETIMES = {
    "VIC_MW008": ("Port Phillip and Western Port", "IDV10465"),
    "WA_MW017": ("Perth and Melville Local Waters", "IDW11500"),
}


def regions(raw: bytes) -> dict:
    """{aac: description} of the region and sub-region areas (the zones' parents) in one product."""
    return {
        a.get("aac"): a.get("description")
        for a in bom_ftp._xml(raw).iter("area")
        if a.get("type") in ("region", "sub-region")
    }


def main():
    files = bom_ftp.Feed().fetch(bom_ftp.FORECASTS)
    zones, names = {}, {}
    for name in bom_ftp.FORECASTS:
        if name in files:
            z, _ = bom_ftp.parse_forecast(files[name])
            for aac, v in z.items():
                zones.setdefault(aac, v)  # keep the first product listing it (the state bundle)
                zones[aac].setdefault("also", set())
                if v["product"] != zones[aac]["product"]:
                    zones[aac]["also"].add(v["product"])
            names.update(regions(files[name]))

    by_state = defaultdict(lambda: defaultdict(list))
    for aac, z in zones.items():
        by_state[aac.split("_")[0]][z["parent"]].append((aac, z))

    out = [
        "# Coastal waters zones",
        "",
        f"The coastal waters zones BOM forecasts ({len(zones)} in the issues of {time.strftime('%d %B %Y')}).",
        "Generated by `tools/list_zones.py` from the live forecast products; run it again if BOM changes its zones.",
        "",
        "Use the code (BOM's AMOC area code) with `bom_db.forecast()`, `bom_db.active_warnings(aac=...)`,",
        "`/api/forecast/<code>` and `examples/my_spot.py --zone <code>`. Local waters zones (bays, harbours,",
        "estuaries) come from their own product, shown in the last column.",
        "",
    ]
    for state in STATE_ORDER + sorted(set(by_state) - set(STATE_ORDER)):
        if state not in by_state:
            continue
        out += [f"## {state}", ""]
        for parent in sorted(by_state[state], key=lambda p: p or ""):
            out += [f"**{names.get(parent) or parent}** (`{parent}`)", "", "| Code | Zone | Product |", "|---|---|---|"]
            for aac, z in sorted(by_state[state][parent]):
                kind = "local waters" if z["product"] in LOCAL else "coastal waters"
                also = f", also {', '.join(sorted(z['also']))}" if z["also"] else ""
                out.append(f"| `{aac}` | {z['name']} | {z['product']} ({kind}{also}) |")
            out.append("")
    missing = {k: v for k, v in SOMETIMES.items() if k not in zones}
    if missing:
        out += ["## Combined zones in some issues only", "",
                "These cover two local waters zones together and only carry a forecast in some issues.", "",
                "| Code | Zone | Product |", "|---|---|---|"]
        out += [f"| `{k}` | {n} | {p} (local waters) |" for k, (n, p) in sorted(missing.items())]
        out.append("")
    out.append("© Commonwealth of Australia, Bureau of Meteorology.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
